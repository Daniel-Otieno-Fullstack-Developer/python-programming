# One variable of each basic type
name = "Hodan Abdi"        # str   - text
age = 19                   # int   - whole number
fees_paid = 18500.50       # float - number with a decimal point
is_registered = True       # bool  - True or False

print("STUDENT PROFILE")
print("---------------")
# type() tells us which kind of value each variable holds
print("Name:      ", name, type(name))
print("Age:       ", age, type(age))
print("Fees paid: ", fees_paid, type(fees_paid))
print("Registered:", is_registered, type(is_registered))
