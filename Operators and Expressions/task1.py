a = int(input("First whole number: "))
b = int(input("Second whole number: "))

# One line for each arithmetic operator
print("a + b  =", a + b)
print("a - b  =", a - b)
print("a * b  =", a * b)
print("a / b  =", a / b)
print("a // b =", a // b)    # whole-number division
print("a % b  =", a % b)     # remainder
print("a ** b =", a ** b)    # a to the power of b
